import { writeFile } from 'node:fs/promises';
import { createServer } from 'vite';

async function loadColorUtilities() {
  // This release uses extensionless imports internally, so resolve it with the
  // same bundler as the app instead of Node's stricter ESM resolver.
  const server = await createServer({
    configFile: false,
    cacheDir: '.cache/theme-generator',
    logLevel: 'error',
    server: { middlewareMode: true, watch: null, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] },
    ssr: { noExternal: ['@material/material-color-utilities'] },
  });
  try {
    return await server.ssrLoadModule('@material/material-color-utilities');
  } finally {
    await server.close();
  }
}
const { argbFromHex, Hct, hexFromArgb, SchemeTonalSpot } = await loadColorUtilities();

// Generate at design time so the full color engine is not shipped to each client.
const seed = '#386a5c';
const successSeed = '#386a38';
const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'surface', 'onSurface', 'onSurfaceVariant', 'surfaceContainerLowest',
  'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'inverseSurface', 'inverseOnSurface',
];

const themes = [false, true].map((dark) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const success = new SchemeTonalSpot(Hct.fromInt(argbFromHex(successSeed)), dark, 0);
  const properties = roles.map((role) => {
    const name = role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
    return `  --md-sys-color-${name}: ${hexFromArgb(scheme[role])};`;
  });
  for (const [name, role] of [['success', 'primary'], ['success-container', 'primaryContainer'], ['on-success-container', 'onPrimaryContainer']]) {
    properties.push(`  --color-${name}: ${hexFromArgb(success[role])};`);
  }
  return `${dark ? ':root[data-theme="dark"]' : ':root'} {\n${properties.join('\n')}\n}`;
});

const shared = `:root {
  --shape-small: 8px;
  --shape-medium: 12px;
  --shape-large: 24px;
  --shape-extra-large: 28px;
  --motion-short: 160ms cubic-bezier(.2, 0, 0, 1);
  --motion-medium: 260ms cubic-bezier(.2, 0, 0, 1);
  --state-hover: color-mix(in srgb, var(--md-sys-color-on-surface) 8%, transparent);
  --connection-surface: color-mix(in srgb, var(--md-sys-color-primary-container) 42%, var(--md-sys-color-surface-container-low));
}`;

const output = `/* Generated by pnpm theme:generate. Edit scripts/generate-theme.mjs. */\n${themes.join('\n\n')}\n\n${shared}\n`;
await writeFile(new URL('../src/theme/tokens.css', import.meta.url), output);
